CREATE TABLE public.campus_lost_items (
    id uuid PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('lost', 'found')),
    title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 120),
    location text NOT NULL CHECK (char_length(btrim(location)) BETWEEN 1 AND 180),
    published_at timestamptz NOT NULL DEFAULT now(),
    archived_at timestamptz
);

ALTER TABLE public.campus_lost_reports ADD COLUMN item_id uuid
    REFERENCES public.campus_lost_items(id) ON UPDATE CASCADE ON DELETE SET NULL;
CREATE INDEX campus_lost_reports_item ON public.campus_lost_reports (item_id);
ALTER TABLE public.campus_lost_items ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.campus_lost_items FROM PUBLIC;
DO $security$
DECLARE role_name text;
BEGIN
    FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname=role_name) THEN
            EXECUTE format('REVOKE ALL ON public.campus_lost_items FROM %I', role_name);
        END IF;
    END LOOP;
END;
$security$;

